/**
 * Get all mandis for a commodity
 */
export const getAllMandisForCommodity = (commodity) => {
  const commodityKey = commodity.toLowerCase();
  if (mandiDatabase[commodityKey]) {
    const allMandis = [];
    for (const [state, mandis] of Object.entries(mandiDatabase[commodityKey])) {
      allMandis.push(...mandis);
    }
    return allMandis;
  }
  return [];
};

/**
 * Get mandis by state
 */
export const getMandisByState = (commodity, state) => {
  const commodityKey = commodity.toLowerCase();
  if (mandiDatabase[commodityKey] && mandiDatabase[commodityKey][state]) {
    return mandiDatabase[commodityKey][state];
  }
  return [];
};

/**
 * Search mandi by name
 */
export const searchMandi = (commodity, searchTerm) => {
  const allMandis = getAllMandisForCommodity(commodity);
  return allMandis.filter(mandi =>
    mandi.name.toLowerCase().includes(searchTerm.toLowerCase())
  );
};

/**
 * Get unique states for a commodity
 */
export const getStatesForCommodity = (commodity) => {
  const commodityKey = commodity.toLowerCase();
  if (mandiDatabase[commodityKey]) {
    return Object.keys(mandiDatabase[commodityKey]);
  }
  return [];
};

export default {
  mandiDatabase,
  getAllMandisForCommodity,
  getMandisByState,
  searchMandi,
  getStatesForCommodity
};
